/**
 * @param {import('@deepseek-ai/dsh').Context} ctx - host context carrying the system-prompt registry.
 */
function apply(ctx) {
  ctx.systemPrompt.section({
    name: 'local:xhs-style',
    order: 120,
    text: STYLE_GUIDE,
  });
  ctx.logger?.('dsh-xhs-style')?.info?.('xhs-style prompt section registered');
}

export { apply, inject };

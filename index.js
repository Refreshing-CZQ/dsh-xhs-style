/**
 * @param {import('@deepseek-ai/dsh').Context} ctx - host context carrying the system-prompt registry.
 */
function apply(ctx) {
  ctx.systemPrompt.section({
    name: 'local:xhs-requirements-discovery',
    order: 110,
    text: DISCOVERY_GUIDE,
  });
  ctx.systemPrompt.section({
    name: 'local:xhs-style',
    order: 120,
    text: STYLE_GUIDE,
  });
  ctx.logger?.('dsh-xhs-style')?.info?.('requirements-discovery and xhs-style prompt sections registered');
}

export { apply, inject };
